import {test,expect} from '@playwright/test';
const localOnly=async(page:import('@playwright/test').Page)=>{
 await page.route('**/*',route=>new URL(route.request().url()).origin==='http://127.0.0.1:4321'?route.continue():route.abort());
};
test('manual TCP handshake step animates each flight in order, then replays without advancing',async({page})=>{
 await localOnly(page);await page.setViewportSize({width:1440,height:900});
 await page.goto('/learn/concepts/networking/http-request/',{waitUntil:'domcontentloaded'});
 const lab=page.locator('.request-experience');
 await expect(page.locator('astro-island').filter({has:lab})).not.toHaveAttribute('ssr','');
 await page.clock.install();
 const steps=lab.getByRole('navigation',{name:'مراحل درخواست'}).getByRole('button');
 await steps.nth(2).click();
 const chips=lab.locator('.flight-chip'),motion=lab.locator('[data-main-motion=true]');
 await expect(chips).toHaveCount(3);
 await expect(chips.nth(0)).toContainText('SYN seq=100');
 await expect(chips.nth(1)).toContainText('SYN-ACK');
 await expect(chips.nth(2)).toContainText('ACK ack=501');
 await expect(motion).toHaveAttribute('data-flight-count','3');
 await page.clock.runFor(250);
 await expect(chips.nth(0)).toHaveAttribute('data-active','true');
 await page.clock.runFor(1200);
 await expect(chips.nth(1)).toHaveAttribute('data-active','true');
 await page.clock.runFor(1200);
 await expect(chips.nth(2)).toHaveAttribute('data-active','true');
 await page.clock.runFor(1100);
 await expect(motion).toHaveAttribute('data-motion-status','complete');
 await expect(steps.nth(2)).toHaveAttribute('aria-current','step');
 await lab.getByRole('button',{name:'بازپخش همین مرحله'}).click();
 await page.clock.runFor(250);
 await expect(chips.nth(0)).toHaveAttribute('data-active','true');
 await expect(steps.nth(2)).toHaveAttribute('aria-current','step');
 await expect(lab.locator('.state-before').first()).not.toBeEmpty();
 await page.screenshot({path:'test-results/main-motion/http-handshake.png',animations:'disabled'});
 await lab.getByRole('button',{name:'نکته‌ها و منابع',exact:true}).click();
 await expect(motion).toHaveCount(0);
});
test('packet drop differs from a rejected application response and supports reduced motion',async({page})=>{
 await localOnly(page);await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('/learn/concepts/networking/udp/',{waitUntil:'domcontentloaded'});
 const lab=page.locator('[data-lesson=udp]');
 await expect(page.locator('astro-island').filter({has:lab})).not.toHaveAttribute('ssr','');
 await lab.getByLabel('سناریو').selectOption('loss');
 await lab.getByRole('navigation',{name:'مراحل درس'}).getByRole('button').nth(1).click();
 await expect(lab.locator('[data-packet-drop=true]')).toHaveCount(1);
 const droppedFlight=lab.locator('.flow-diagram [data-flight]').filter({has:page.locator('[data-packet-drop=true]')});
 await expect(droppedFlight).toHaveCount(1);
 await expect(droppedFlight.locator('[data-flow-arrow]')).toHaveCount(0);
 await expect(lab.locator('.flight-chip[data-drop=true]')).toHaveCount(1);
 await expect(lab.locator('[data-main-motion=true]')).toHaveAttribute('data-motion-status','complete');
 await page.goto('/learn/concepts/networking/http-status-codes/',{waitUntil:'domcontentloaded'});
 const status=page.locator('[data-lesson=http-status-codes]');
 await expect(page.locator('astro-island').filter({has:status})).not.toHaveAttribute('ssr','');
 await status.getByLabel('سناریو').selectOption('missing');
 await status.getByRole('navigation',{name:'مراحل درس'}).getByRole('button').last().click();
 await expect(status.locator('[data-packet-drop=true]')).toHaveCount(0);
 await expect(status.locator('.flight-chip').first()).toContainText('404');
});
